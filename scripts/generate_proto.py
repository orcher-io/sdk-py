"""Regenerate ``src/orcher/_proto`` from the Orcher protocol definitions.

The worker host hands activations, tasks and actor operations to Python as
encoded ``orcher.kernel.v1`` and ``orcher.host.v1`` messages, and takes the
answers back the same way. The ``.proto`` files are taken from the
``orcher-proto`` crate the native module builds against, so the Python
messages always describe the same protocol as the Rust core. Set
``ORCHER_PROTO_DIR`` to generate from any other directory of ``.proto`` files.

Needs ``protoc`` on PATH and a Rust toolchain (for ``cargo metadata``). Only
this script needs them: the generated code is committed, so building and
testing the SDK do not.

Usage: python scripts/generate_proto.py
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "orcher" / "_proto"
# The messages that cross the native boundary, and what they import.
PROTOS = ["kernel.proto", "host.proto", "client.proto"]


def proto_dir_from_cargo() -> Path:
    metadata = json.loads(
        subprocess.check_output(
            [
                "cargo",
                "metadata",
                "--format-version",
                "1",
                "--manifest-path",
                str(ROOT / "Cargo.toml"),
            ]
        )
    )
    crate = next((p for p in metadata["packages"] if p["name"] == "orcher-proto"), None)
    if crate is None:
        raise SystemExit("orcher-proto is not a dependency of Cargo.toml")
    print(f"using orcher-proto {crate['version']}")
    return Path(crate["manifest_path"]).parent / "proto"


def main() -> None:
    override = os.environ.get("ORCHER_PROTO_DIR")
    proto_dir = Path(override) if override else proto_dir_from_cargo()
    with tempfile.TemporaryDirectory() as scratch:
        subprocess.check_call(
            [
                "protoc",
                f"--proto_path={proto_dir}",
                f"--python_out={scratch}",
                f"--pyi_out={scratch}",
                *PROTOS,
            ]
        )
        # Start clean, so a message removed upstream leaves nothing behind.
        shutil.rmtree(OUT, ignore_errors=True)
        OUT.mkdir(parents=True)
        (OUT / "__init__.py").write_text(
            '"""The kernel and host protocol messages, generated by '
            "``scripts/generate_proto.py``; do not edit.\n\n"
            'This package is internal."""\n'
        )
        for generated in sorted(Path(scratch).iterdir()):
            text = generated.read_text()
            # protoc imports a sibling module as a top-level one; here they
            # live in a package.
            text = re.sub(
                r"^import (\w+_pb2) as (\w+)$",
                r"from . import \1 as \2",
                text,
                flags=re.MULTILINE,
            )
            (OUT / generated.name).write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
